/**
 * Regenerate IMAGES_NEEDED.md from content/images.json and the questions that use each photo.
 *   npm run images:needed
 */
import { writeFileSync } from "node:fs";
import { loadAuthoredItems, loadImageManifest } from "../lib/content/load";

export function buildImagesNeeded(): string {
  const images = loadImageManifest();
  const items = loadAuthoredItems();
  const groups = [...new Set(images.map((i) => i.group))];
  let md = `# Images needed\n\nGenerated by \`npm run images:needed\`. Do not edit by hand; edit \`content/images.json\` instead.\n\n`;
  md += `**${images.length} photos** are used by **${items.filter((i) => i.imageIds.length).length} questions**. A question stays hidden from tests until all its photos are uploaded.\n\n`;
  md += `## How to add a photo\n\n1. Sign in as the mentor and open **Images**.\n2. Find the photo by its ID and tap **Upload**. You can take the picture right there with the phone camera.\n3. It is compressed automatically and the questions that use it go live.\n\n`;
  md += `**Rules:** shoot it yourself, or use only open-licence photos (Wikimedia Commons, Unsplash, Pexels, Pixabay) and record the licence, author and link. Never use Google Images or coaching-site pictures. Don't include people's faces, number plates or brand logos as the main subject.\n\n`;
  for (const g of groups) {
    md += `## ${g}\n\n| ID | What to shoot | How | Aspect | Used by |\n|---|---|---|---|---|\n`;
    for (const img of images.filter((i) => i.group === g)) {
      const users = items.filter((i) => i.imageIds.includes(img.id)).map((i) => i.id);
      const how = img.shotNotes + (img.openSource ? ` *Alternative: ${img.openSource} (record licence).*` : "");
      md += `| \`${img.id}\` | ${img.description} | ${how} | ${img.aspect} | ${users.join(", ")} |\n`;
    }
    md += "\n";
  }
  return md;
}

if (process.argv[1]?.endsWith("images-needed.ts")) {
  writeFileSync("IMAGES_NEEDED.md", buildImagesNeeded());
  console.log("✓ wrote IMAGES_NEEDED.md");
}
