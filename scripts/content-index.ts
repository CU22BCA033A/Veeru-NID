/**
 * Regenerate content/index.ts, which statically imports every content JSON file so that
 * Vercel bundles them (no runtime fs reads).  npm run content:index
 */
import { readdirSync, writeFileSync } from "node:fs";

export function buildContentIndex(): string {
  const dirs = ["items", "studio", "mocks", "concepts"] as const;
  const lines = ["// Generated by `npm run content:index`. Do not edit by hand.", ""];
  const exports: Record<string, string[]> = {};
  for (const dir of dirs) {
    let files: string[] = [];
    try {
      files = readdirSync(`content/${dir}`).filter((f) => f.endsWith(".json")).sort();
    } catch {
      files = [];
    }
    exports[dir] = [];
    for (const f of files) {
      const name = `${dir}_${f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]/g, "_")}`;
      lines.push(`import ${name} from "./${dir}/${f}";`);
      exports[dir].push(name);
    }
  }
  lines.push("");
  for (const [dir, names] of Object.entries(exports)) {
    lines.push(`export const ${dir}Files: unknown[] = [${names.join(", ")}];`);
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1]?.endsWith("content-index.ts")) {
  writeFileSync("content/index.ts", buildContentIndex());
  console.log("✓ wrote content/index.ts");
}
